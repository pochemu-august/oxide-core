//! ⚙️ config.rs — Все константы тюнинга и баланса oxide-core.
//!
//! Содержит параметры арены, игрока, физики движения, рывка, стрельбы,
//! прицеливания, камеры, времени жизни визуальных эффектов и базовую цветовую палитру.

use bevy::prelude::*;

// ============================================================================
// АРЕНА
// ============================================================================

pub const ARENA_SIZE: f32 = 100.0;
pub const ARENA_HALF: f32 = ARENA_SIZE / 2.0;
pub const WALL_THICKNESS: f32 = 1.0;
pub const WALL_HEIGHT: f32 = 2.5;

// ============================================================================
// ИГРОК
// ============================================================================

pub const PLAYER_SIZE: Vec3 = Vec3::new(0.8, 1.6, 0.8);
/// Стартовая позиция игрока в мире (центр арены, стоит на земле).
pub const PLAYER_START: Vec3 = Vec3::new(0.0, PLAYER_SIZE.y / 2.0, 0.0);
/// Радиус игрока для коллизий (круг в плоскости XZ).
pub const PLAYER_RADIUS: f32 = 0.5;
/// Локальная позиция "носа" (вперёд в Bevy — это -Z).
pub const NOSE_LOCAL: Vec3 = Vec3::new(0.0, 0.3, -0.55);
pub const NOSE_SIZE: Vec3 = Vec3::new(0.25, 0.25, 0.5);
/// Кончик носа — точка спавна снарядов и начала лазерного луча.
pub const NOSE_TIP_LOCAL: Vec3 = Vec3::new(0.0, NOSE_LOCAL.y, NOSE_LOCAL.z - NOSE_SIZE.z / 2.0);

// ============================================================================
// ДВИЖЕНИЕ (Ultrakill-like: мгновенный разгон и резкое торможение)
// ============================================================================

pub const MOVE_SPEED: f32 = 12.0;
/// Ускорение при наличии ввода (ед/с²).
pub const ACCELERATION: f32 = 120.0;
/// Торможение без ввода (ед/с²). Высокое значение устраняет "эффект скольжения по льду".
pub const FRICTION: f32 = 160.0;

// ============================================================================
// РЫВОК (DASH)
// ============================================================================

pub const DASH_SPEED: f32 = 42.0;
pub const DASH_DURATION: f32 = 0.14;
pub const DASH_COOLDOWN: f32 = 0.5;
/// Скорость, с которой игрок выходит из рывка (сохраняет динамику).
pub const DASH_EXIT_SPEED: f32 = MOVE_SPEED * 1.2;

// ============================================================================
// СТРЕЛЬБА
// ============================================================================

pub const PROJECTILE_SPEED: f32 = 45.0;
pub const PROJECTILE_LIFETIME: f32 = 1.5;
pub const PROJECTILE_RADIUS: f32 = 0.15;
/// Задержка между выстрелами при зажатой ЛКМ (10 выстрелов в секунду).
pub const FIRE_COOLDOWN: f32 = 0.1;

// ============================================================================
// ПРИЦЕЛИВАНИЕ
// ============================================================================

/// Высота плоскости проекции луча курсора (на высоте ствола/носа игрока).
pub const AIM_PLANE_Y: f32 = PLAYER_SIZE.y / 2.0 + NOSE_LOCAL.y;

// ============================================================================
// КАМЕРА
// ============================================================================

/// Смещение камеры относительно игрока (высота Y: 15.0, наклон Z: 10.0 => ~56° к земле).
pub const CAMERA_OFFSET: Vec3 = Vec3::new(0.0, 15.0, 10.0);
/// Жёсткость сглаживания следования (Frame-rate independent LERP).
pub const CAMERA_SMOOTHNESS: f32 = 8.0;

// ============================================================================
// ВИЗУАЛЬНЫЕ ЭФФЕКТЫ И ЧАСТИЦЫ
// ============================================================================

pub const DASH_GHOST_LIFETIME: f32 = 0.22;
pub const SPARK_LIFETIME: f32 = 0.35;

// ============================================================================
// ЦВЕТОВАЯ ПАЛИТРА (Low-Poly Retro)
// ============================================================================

pub const COLOR_GROUND: Color = Color::srgb(0.16, 0.16, 0.18);
pub const COLOR_WALL: Color = Color::srgb(0.09, 0.09, 0.11);
pub const COLOR_RED: Color = Color::srgb(0.75, 0.12, 0.10);
pub const COLOR_ORANGE: Color = Color::srgb(0.95, 0.45, 0.08);
pub const COLOR_PLAYER: Color = Color::srgb(0.15, 0.35, 0.95);
pub const COLOR_SKY: Color = Color::srgb(0.04, 0.04, 0.06);

// ============================================================================
// ВРАГИ И ЗДОРОВЬЕ
// ============================================================================

pub const ENEMY_SIZE: Vec3 = Vec3::new(1.0, 1.4, 1.0);
pub const ENEMY_RADIUS: f32 = 0.55;
pub const ENEMY_SPEED: f32 = 6.5;
pub const ENEMY_HEALTH: f32 = 30.0;
pub const PROJECTILE_DAMAGE: f32 = 15.0;
pub const COLOR_ENEMY: Color = Color::srgb(0.92, 0.12, 0.14);
pub const COLOR_ENEMY_EYE: Color = Color::srgb(1.0, 0.85, 0.1);
pub const MAX_ENEMIES: usize = 12;
pub const ENEMY_SPAWN_INTERVAL: f32 = 2.5;

// ============================================================================
// ЗДОРОВЬЕ И УРОН
// ============================================================================

pub const PLAYER_MAX_HEALTH: f32 = 100.0;
pub const ENEMY_ATTACK_DAMAGE: f32 = 25.0;
pub const PLAYER_INVULN_AFTER_HIT: f32 = 0.5;
pub const COLOR_PLAYER_HURT: Color = Color::srgb(1.0, 0.2, 0.2);
